  HAL_GPIO_Init(GPIOE, &g);                                    // restore the SAI function
#endif

  if (!audio_start()){
  	  printf("DMA initialization failed!\n");
  	  return -1;
    }
  int gain = -5, DAC_gain = 0;
  codec_set_intput_gain(gain);
  codec_set_ADC_gain(gain);
  codec_set_DAC_gain(DAC_gain);
  codec_set_output_gain(gain);
  #endif
#ifdef FILTER
  // ... System Init, CMSIS-DSP Setup ...

  // Set filter to Lowpass 1kHz at runtime
  update_my_FIR_filter(FILTER_LOWPASS, 1000.0f, 0.0f, 46875.0f);
#endif
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
	  #ifdef TUNER
	  printf("\nGetting signal...\n");
	  // ADC value to complex_t array conversion
	  get_input_signal(tune_signal, n_tune);
	  printf("\nProcessing signal...\n");
	  // Apply window to reduce spectral leakage
	  //	  apply_window_hann(signal, n);
	  // Process signal with FFT
	  //	  memcpy(spectrum, signal, n * sizeof(complex_t));
	  radix2_dif_fft(tune_signal, n_tune, FFT_FORWARD);
	  printf("\nGetting frequency...\n");
	  double pitch_hps = detect_pitch_hps(tune_signal, n_tune, sample_rate, 3);
	  //	  double pitch_autocorr = detect_pitch_autocorr(signal, n, sample_rate);
	  //	  printf("True frequency: 440.00 Hz (A4)\n");
	  printf("HPS method: %.2f Hz\n", pitch_hps);
	  //	  printf("Autocorrelation: %.2f Hz (error: %.2f Hz)\n",
	  //		  pitch_autocorr, pitch_autocorr - 440);
	  // code for tuning)
	  printf(frequency_to_note_name(pitch_hps));
	  //	  HAL_Delay(1);
	  #endif

	  #ifdef PEDAL_EFFECTS
	  if(!input_from_codec(effect_signal, n_effects)) continue;
  //	  get_input_MCU_signal(effect_signal, n_effects);
	  // Example: Add effects to the chain
	  params wah_params = {true, {50}}; // Example Wah, enabled, 50%
	  chain_length = append_effect(E_WAH, wah_params, effect_chain, chain_length);
	  // Apply the effect chain to the signal
	  apply_effect_chain(effect_signal, n_effects, effect_chain, chain_length);
	  // Output the processed signal (implementation depends on hardware)
	  output2codec(effect_signal, n_effects);
	  #endif
	  #ifdef CODEC
	  // Get input signal from ADC
//	  printf("\nGetting signal...\n");
//	  if(!input_from_codec(effect_signal, n_effects))
//		  continue;
	  get_input_MCU_signal(effect_signal, n_effects);
	  // send signal to codec for output (testing no effects latency)
//	  printf("\nOutputting signal...\n");
	  output2codec(effect_signal, n_effects);
	  #endif
#ifdef FILTER
	  // If an event or user changes a setting, simply call update_my_filter again!
	  	  input_from_codec(effect_signal, n_effects);
	  //	  get_input_MCU_signal(effect_signal, n_effects);

	  	  //filter
	  	Process_DSP_Block(&effect_signal[0],&effect_signal[0]);
	  	  // send signal to codec for output (testing no effects latency)
	  	  output2codec(effect_signal, n_effects);
#endif
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  free_complex_array(tune_signal_cplx);
  free_complex_array(effect_signal_cplx);
  /* USER CODE END 3 */
